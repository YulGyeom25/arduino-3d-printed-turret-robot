import numpy as np
import matplotlib.pyplot as plt

"""###상수 값들 입력"""

rho = 1.2          # air density [kg/m^3]
Cd = 0.47          # ping-pong ball drag coefficient (initial guess)
m = 0.0027         # ball mass [kg]
r_ball = 0.02      # ball radius [m]
A = np.pi * r_ball**2
R_wheel = 0.03     # wheel radius [m] (diameter 6 cm)

dt = 0.001
T_end = 1.0

"""###WHEEL RPM 입력"""

rpm1 = 6000
rpm2 = 1000

# 3. 휠 표면속도
# =========================
v1 = 2 * np.pi * R_wheel * rpm1 / 60
v2 = 2 * np.pi * R_wheel * rpm2 / 60

# =========================
# 4. 초기 공 속도 / 회전
# =========================
v0 = (v1 + v2) / 2
omega = (v1 - v2) / (2 * r_ball)   # rad/s
ball_rpm = omega * 60 / (2 * np.pi)

"""### 초기 상태 정의"""

x = 0.0
y = 0.0

vx = v0      # 전진 방향 초기속도
vy = 0.0     # 측면 방향 초기속도

xs = []
ys = []
vxs = []
vys = []
times = []

"""### 시뮬레이션

"""

# 6. 뉴턴 방정식을 사용한 시뮬레이션

for t in np.arange(0, T_end, dt):
    v = np.sqrt(vx**2 + vy**2)
    if v < 1e-8:
        break

    # spin ratio
    S = omega * r_ball / v

    # lift coefficient (simple approximation)
    CL = 0.4 * S

    # Drag force magnitude
    FD = 0.5 * rho * Cd * A * v**2

    # Drag force components
    FDx = -FD * (vx / v)
    FDy = -FD * (vy / v)

    # Magnus force magnitude
    FM = 0.5 * rho * CL * A * v**2

    # 단순 2D 측면 커브 모델: Magnus는 +y 방향
    FMx = 0.0
    FMy = FM

    # Total acceleration
    ax = (FDx + FMx) / m
    ay = (FDy + FMy) / m

    # Update velocity
    vx += ax * dt
    vy += ay * dt

    # Update position
    x += vx * dt
    y += vy * dt

    xs.append(x)
    ys.append(y)
    vxs.append(vx)
    vys.append(vy)
    times.append(t)

    # 목표 거리쯤에서 종료하고 싶으면
    if x >= 1.5:   # 1.5 m
        break

"""### 결과 출력"""

# =========================
# 7. 결과 출력
# =========================
print("\n===== Final State =====")
print(f"final x = {x:.3f} m")
print(f"final y = {y:.3f} m")
print(f"final vx = {vx:.3f} m/s")
print(f"final vy = {vy:.3f} m/s")

# =========================
# 8. 궤적 그래프
# =========================
plt.figure(figsize=(8,5))
plt.plot(xs, ys, label='Simulated trajectory')
plt.xlabel('x [m] (forward)')
plt.ylabel('y [m] (sideways)')
plt.title('2D trajectory with drag + Magnus')
plt.grid(True)
plt.legend()
plt.show()

